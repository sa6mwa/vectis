local sqlite = require("vectis.sqlite")
local db <close> = assert(sqlite.open(":memory:"))
assert(db:exec("create table item (id INTEGER PRIMARY KEY, name TEXT)", {}))
assert(db:transaction(function(connection)
  assert(connection:exec("insert into item values (?,?)", {1, "example"}))
end))
local rows <close> = assert(db:query("select id,name from item order by id", {}))
local row = assert(rows:next())
assert(row[1] == 1 and row[2] == "example")
local eof, err = rows:next()
assert(eof == nil and err == nil)
local json <close> = assert(db:query("select format('%J',name) from item", {}))
assert(json:next()[1] == '"example"')
print("SQLite example ok")
