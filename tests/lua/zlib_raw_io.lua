local invalid,error=owner:set_output(readonly);assert(invalid==nil)
readonly:close();owner:set_input(buffer);owner:set_output(buffer)
local invalid,error=owner:run(z.Z_NO_FLUSH);assert(invalid==nil and error.message:find('overlap',1,true))
owner:set_input(nil);owner:set_output(nil);assert(buffer:resize(64)==buffer)
