local z=require('zlib');local bytes=require('vectis.buffer')
local function fails(fn,...) assert(not pcall(fn,...)) end
local message=('bound input '):rep(20)
local input=assert(bytes.from_materialized(message));local output=assert(bytes.new(512))
local encoder=assert(z.deflateInit(6))
assert(encoder:deflateBound(#message)>=#message and z.deflateBound_z(encoder,#message)==encoder:deflateBound(#message))
local native_bound=encoder:deflateBound_z(z.Z_SIZE_MAX)
assert(type(native_bound)=='number' or type(native_bound)=='string')
fails(encoder.deflateBound,encoder,-1);fails(encoder.deflateBound_z,encoder,'18446744073709551616')
assert(encoder:set_input(input)==encoder and encoder:set_output(output)==encoder)
local before=encoder:fields()
assert(before.avail_in==#message and before.next_in:size()==#message)
assert(before.avail_out==512 and before.next_out:size()==512)
fails(before.next_in.write,before.next_in,0,'x')
before.next_in:close();before.next_out:close()
fails(input.resize,input,512);fails(output.resize,output,1024)
local failed,error=encoder:process_materialized('x',128,z.Z_FINISH)
assert(failed==nil and error.status~=0)
assert(encoder:set_avail_in(#message)==encoder)
local invalid,error=encoder:set_avail_in(#message+1);assert(invalid==nil)
local fork=assert(encoder:copy())
encoder:close();input:close();collectgarbage('collect')
local result=assert(fork:run(z.Z_FINISH))
assert(result.zlib_status==z.Z_STREAM_END and result.consumed==#message)
local compressed=output:read_materialized(0,result.produced)
local after=fork:fields()
assert(after.avail_in==0 and after.next_in:size()==0)
assert(after.avail_out==512-result.produced and after.next_out:size()==after.avail_out)
after.next_in:close();after.next_out:close()
fork:close();assert(output:resize(1024)==output);output:close()
local source=assert(bytes.from_materialized(compressed));local destination=assert(bytes.new(#message))
local decoder=assert(z.inflateInit())
decoder:set_input(source);decoder:set_output(destination)
source:close();collectgarbage('collect')
assert(decoder:run(z.Z_FINISH).zlib_status==z.Z_STREAM_END)
assert(destination:read_materialized(0,#message)==message)
decoder:close();assert(destination:resize(1)==destination);destination:close()
-- Params can produce output. A retry after BUF_ERROR must retain state and
-- apply the change with real caller-provided output capacity.
local raw=assert(z.deflateInit(1));local data=assert(bytes.from_materialized(('a'):rep(1000)))
local sink=assert(bytes.new(2048));raw:set_input(data);raw:set_output(sink)
assert(raw:run(z.Z_NO_FLUSH).consumed==1000)
local total=raw:fields().total_out
assert(raw:set_output(sink,total,0)==raw)
local pending=assert(z.deflateParams(raw,9,z.Z_DEFAULT_STRATEGY))
assert(pending.zlib_status==z.Z_BUF_ERROR)
raw:set_output(sink,total,2048-total)
local changed=assert(raw:deflateParams(9,z.Z_DEFAULT_STRATEGY));assert(changed.zlib_status==z.Z_OK)
local finished=assert(raw:run(z.Z_FINISH));assert(finished.zlib_status==z.Z_STREAM_END)
local length=raw:fields().total_out
assert(z.inflate_materialized(sink:read_materialized(0,length))==('a'):rep(1000))
local fields=raw:fields();fields.next_in:close();fields.next_out:close()
raw:close();data:close();sink:close()
-- Output readonly, range, uint narrowing and overlapping IO fail without
-- losing existing bindings; explicit unbind releases owned leases.
