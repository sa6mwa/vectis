local sqlite = require('vectis.sqlite')
local vectis = require('vectis')
assert(vectis.sqlite == sqlite)
assert(require('vectis.sql').NULL == sqlite.NULL)
assert(require('vectis.pg').NULL == sqlite.NULL)
local db = assert(sqlite.open(':memory:'))
local upgrade_cases=dofile(assert(os.getenv('VECTIS_SQLITE_UPGRADE_CASES')))
upgrade_cases(db,sqlite.NULL)
local function exec(sql, params) return assert(db:exec(sql, params or {})) end
exec('create table t (id INTEGER PRIMARY KEY, text TEXT, data BLOB, n)')
local inserted = exec('insert into t values (?,?,?,?)',
  {math.maxinteger, 'a\0b', sqlite.blob(''), sqlite.NULL})
assert(inserted.changes == 1 and inserted.last_insert_rowid == math.maxinteger)
local cursor = assert(db:query('select id as name,text as name,data,n,typeof(data),typeof(text) from t', {}))
local columns = assert(cursor:columns())
assert(#columns == 6 and columns[1].name == 'name' and columns[2].name == 'name')
local row = assert(cursor:next())
assert(row[1] == math.maxinteger and row[2] == 'a\0b' and row[3] == '' and row[4] == sqlite.NULL)
assert(row[5] == 'blob' and row[6] == 'text')
local eof, err = cursor:next()
assert(eof == nil and err == nil)
assert(cursor:next() == nil)
assert(cursor:close() and cursor:close())
local s = assert(db:prepare('select ?, ?, ?, ?'))
assert(s:bind({math.mininteger, 1.25, true, sqlite.blob('x\0y')}))
row = assert(s:next())
assert(row[1] == math.mininteger and row[2] == 1.25 and row[3] == 1 and row[4] == 'x\0y')
assert(s:next() == nil)
assert(s:reset())
assert(s:next() == nil) -- bind is mandatory after reset; reports an operational error
assert(s:bind({0, '', false, sqlite.NULL}))
row = assert(s:next())
assert(row[1] == 0 and row[2] == '' and row[3] == 0 and row[4] == sqlite.NULL)
assert(s:close())
local function count()
  local c <close> = assert(db:query('select count(*) from t', {}))
  return assert(c:next())[1]
end
local n = count()
exec('BEGIN')
local before, before_error = db:transaction(function() error('must not run') end)
assert(before == nil and before_error.transaction_outcome == 'not_started')
assert(db:transaction_diagnostic().transaction_outcome == 'not_started')
exec('ROLLBACK')
local ok, a, b = db:transaction(function(connection)
  assert(connection == db)
  exec('insert into t values (?,?,?,?)', {1,'ok',sqlite.blob('ok'),sqlite.NULL})
  return 'saved', 42
end, {mode='IMMEDIATE'})
assert(ok and a == 'saved' and b == 42 and count() == n+1)
assert(db:transaction_diagnostic().transaction_outcome == 'committed')
ok, err = db:transaction(function()
  exec('insert into t values (?,?,?,?)', {2,'no',sqlite.blob('no'),sqlite.NULL})
  return nil, 'rollback requested'
end)
assert(ok == nil and err.cause == 'rollback requested' and err.transaction_outcome == 'rolled_back')
assert(db:transaction_diagnostic().transaction_outcome == 'rolled_back')
local nested, nested_error = db:transaction(function()
  local inner, inner_error = db:transaction(function() error('must not run') end)
  assert(inner == nil and inner_error.transaction_outcome == 'not_started')
end)
assert(nested == nil and nested_error.transaction_outcome == 'rolled_back')
assert(count() == n+1)
-- SQLite itself may roll back a failed statement's transaction.
ok, err = db:transaction(function()
  return db:exec('insert or rollback into t values (?,?,?,?)',
    {math.maxinteger,'duplicate',sqlite.blob(''),sqlite.NULL})
end)
assert(ok == nil and err.transaction_outcome == 'rolled_back')
assert(count() == n+1)
local marker = {}
ok, err = pcall(function() db:transaction(function()
  exec('delete from t')
  error(marker)
end) end)
assert(not ok and err == marker and count() == n+1)
ok, err = db:transaction(function() assert(db:close() == nil) end)
assert(ok == nil and err.transaction_outcome == 'rolled_back')
ok, err = db:transaction(function() assert(db:exec('COMMIT', {}) == nil) end)
assert(ok == nil and err.transaction_outcome == 'rolled_back')
local escaped
ok, err = db:transaction(function() escaped = assert(db:query('select 1', {})) end)
assert(ok == nil and err.transaction_outcome == 'rolled_back' and escaped:next() == nil)
assert(escaped:close())
for _, sql in ipairs({'select 1; select 2', 'delete from t; PRAGMA user_version=8', '', '-- comment'}) do
  assert(db:query(sql, {}) == nil)
end
assert(count() == n+1)
assert(db:exec('select * from t', {}) == nil)
assert(db:exec('insert into t values (?,?,?,?)', {}) == nil)
for _, invalid in ipairs({{[1]=1,[3]=3}, {x=1}, {function() end}}) do
  assert(not pcall(function() db:query('select ?', invalid) end))
end
assert(not pcall(function() db:query('select 1\0;select 2', {}) end))
assert(not pcall(function() sqlite.open(':memory:', {unexpected=true}) end))
assert(sqlite.open('/vectis-test-no-such-directory/file.db', {mode='readonly'}) == nil)
-- Failed steps remain errors on subsequent reads, never successful EOF.
local failed = assert(db:query('insert into t values (?,?,?,?) returning id',
  {math.maxinteger,'duplicate',sqlite.blob(''),sqlite.NULL}))
local value, failure = failed:next()
assert(value == nil and failure.dependency_code ~= 0)
local _, repeated = failed:next()
assert(repeated.dependency_code == failure.dependency_code)
assert(failed:close())
-- Explicit paths persist; readonly and zero-wait contention propagate.
local path = assert(os.getenv('VECTIS_UPGRADE_TEST_ROOT')) .. '/data.sqlite'
local first <close> = assert(sqlite.open(path))
assert(first:exec('create table persisted (value)', {}))
assert(first:exec('insert into persisted values (?)', {'saved'}))
local second <close> = assert(sqlite.open(path, {busy_timeout_ms=0}))
assert(first:exec('BEGIN IMMEDIATE', {}))
local blocked, busy = second:exec('insert into persisted values (?)', {'blocked'})
assert(blocked == nil and busy.dependency_code == 5)
assert(first:exec('ROLLBACK', {}))
assert(second:close() and first:close())
local readonly <close> = assert(sqlite.open(path, {mode='readonly'}))
assert(readonly:exec('delete from persisted', {}) == nil)
local saved <close> = assert(readonly:query('select value from persisted', {}))
assert(saved:next()[1] == 'saved' and saved:next() == nil)
local held = assert(db:query('select 1', {}))
assert(db:close() and db:close())
assert(held:next() == nil)
assert(held:close())
db = nil
collectgarbage('collect')
collectgarbage('collect')
local app = assert(vectis.app.new({tls={mode='disabled'}}))
local app_path = assert(os.getenv('VECTIS_UPGRADE_TEST_ROOT')) .. '/app.sqlite'
local options = {name='application',path=app_path}
local owned = assert(app:sqlite(options))
assert(io.open(app_path, 'rb') == nil)
options.path = '/vectis-no-such-directory/wrong.db'
options.name = 'changed'
assert(owned:exec('create table app_data (value)', {}) == nil)
assert(app:sqlite({name='application',path=':memory:'}) == nil)
assert(app:start())
upgrade_cases(owned,sqlite.NULL)
assert(owned:exec('create table app_data (value)', {}))
assert(owned:exec('insert into app_data values (?)', {'persistent'}))
assert(app:sqlite({name='late',path=':memory:'}) == nil)
for _, method in ipairs({'stop','restart','start','close','run'}) do
  ok, err = owned:transaction(function()
    assert(not pcall(app[method], app), method..' must reject callback lifecycle changes')
  end)
  assert(ok == nil and err.transaction_outcome == 'rolled_back', method)
end
local old = assert(owned:query('select value from app_data', {}))
assert(app:stop())
assert(old:next() == nil)
assert(owned:query('select value from app_data', {}) == nil)
assert(app:start())
local current = assert(owned:query('select value from app_data', {}))
assert(current:next()[1] == 'persistent')
assert(current:close() and old:close())
assert(app:restart())
app:close()
assert(owned:query('select value from app_data', {}) == nil)
assert(owned:close())
app, owned = nil, nil
collectgarbage('collect')
collectgarbage('collect')
print('upgrade seam behavior ok')
