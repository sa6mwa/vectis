local z=require('zlib')
local root=assert(os.getenv('VECTIS_UPGRADE_TEST_ROOT'))
local path=root..'/data.gz'
local function open(mode) return assert(z.gzopen(path,mode)) end
for _,bad in ipairs({'', 'r+', 'q'}) do local g,e=z.gzopen(path,bad); assert(g==nil and e.code) end
assert(not pcall(z.gzopen,path..'\0x','wb'))
assert(not pcall(z.gzdopen,1.0,'rb'))
assert(not pcall(z.gzdopen,-1,'rb'))
local g,e=z.gzopen(root..'/missing/no','rb'); assert(not g and e.errno~=0)
g=open('wb'); assert(g:buffer(32)==0); assert(g:write('a\0b')==3)
assert(g:buffer(32)==-1); assert(g:setparams(1,z.Z_FILTERED)==0)
assert(g:flush(z.Z_SYNC_FLUSH)==0); assert(g:puts('c\0ignored')==1)
assert(g:putc(10)==10); assert(g:fwrite('de',1,2)==2)
assert(g:tell()==7 and g:tell64()==7); assert(g:close_r()==z.Z_STREAM_ERROR)
local bad,berr=g:read(1); assert(not bad and berr.code==z.Z_STREAM_ERROR)
assert(g:write('f')==1); assert(g:close_w()==0 and g:close()==0)
local r=open('rb'); assert(r:buffer(32)==0); assert(r:direct()==0)
assert(r:read(0)==''); assert(r:read(3)=='a\0b'); assert(r:getc()==99)
assert(r:ungetc(99)==99); assert(r:getc_()==99); assert(r:gets(10)=='\n')
local bytes,count=r:fread(2,3); assert(bytes=='def' and count==1)
assert(r:read(10)==nil); assert(r:error()==0); assert(r:eof()==1)
assert(r:clearerr()==0 and r:eof()==0); assert(r:rewind()==0)
assert(r:seek64(1,0)==1 and r:tell()==1); assert(r:read(2)=='\0b'); assert(r:seek(-0x100000000,0)==-1 and r:tell()==3); assert(not pcall(r.seek,r,1.0,0))
assert(r:seek(math.maxinteger,1)==-1); assert(r:offset64()>=0); assert(r:seek(0,2)==-1)
assert(r:close_w()==z.Z_STREAM_ERROR); assert(r:close_r()==0); assert(r:read(1)==nil)
assert(not pcall(r.read,r,65537)); assert(not pcall(r.read,{},1))
assert(pcall(getmetatable(r).__gc,{})); assert(pcall(getmetatable(r).__gc,io.stdout)); assert(io.type(io.stdout)=="file")
local a=open('ab'); assert(a:write('tail')==4); assert(a:close()==0)
r=open('rb'); assert(r:read(64)=='a\0bc\ndef'..'tail'); assert(r:read(1)==nil)
local resumed=open('ab'); assert(resumed:write('more')==4); resumed:close()
assert(r:clearerr()==0 and r:read(10)=='more'); r:close()
local plain=root..'/plain'; local f=assert(io.open(plain,'wb')); f:write('plain\0text'); f:close()
r=assert(z.gzopen(plain,'rb')); local bad,be=r:write('x'); assert(bad==-1 and be.code==z.Z_STREAM_ERROR); assert(r:direct()==1); assert(r:read(32)=='plain\0text'); r:rewind(); assert(r:gets(32)=='plain' and r:tell()==10); r:close()
r=assert(z.gzopen(plain,'rbG')); local v,err=r:read(32); assert(err and err.code==z.Z_DATA_ERROR); r:close()
-- Tiny truncation: provider reports BUF_ERROR even with partial decoded bytes.
f=assert(io.open(path,'rb')); local data=f:read('*a'); f:close()
f=assert(io.open(root..'/truncated','wb')); f:write(data:sub(1,-5)); f:close()
r=assert(z.gzopen(root..'/truncated','rb')); v,err=r:read(64); assert(err and err.code==z.Z_BUF_ERROR)
assert(r:close()==z.Z_BUF_ERROR and r:close()==z.Z_BUF_ERROR)
f=assert(io.open(root..'/corrupt','wb')); f:write(data:sub(1,-9)..string.char((data:byte(-8)+1)%256)..data:sub(-7)); f:close()
r=assert(z.gzopen(root..'/corrupt','rb')); v,err=r:read(64); assert(err and err.code~=0); r:close()
do local h <close> = open('rb'); assert(h:read(1)=='a') end
for i=1,4 do local h=open('rb'); h:read(1) end; collectgarbage('collect')
local empty=assert(z.gzopen(root..'/empty','wb')); assert(empty:write('')==0); empty:close()
empty=assert(z.gzopen(root..'/empty','rb')); assert(empty:read(1)==nil); empty:close()
for _,p in ipairs({path,plain,root..'/truncated',root..'/corrupt',root..'/empty'}) do assert(os.remove(p)) end
print('upgrade seam behavior ok')
