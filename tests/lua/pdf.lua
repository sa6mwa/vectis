local pdf = require('vectis.pdf')
local vectis = require('vectis')
assert(vectis.pdf == pdf)
local fixtures = assert(os.getenv('VECTIS_PDF_FIXTURES'))
local root = assert(os.getenv('VECTIS_UPGRADE_TEST_ROOT'))
local options = {title='Lua report',author='Vectis',subject='Public API'}
local doc = assert(pdf.new(options))
options.title = 'changed after construction'
local page = assert(doc:add_page({width=320,height=240}))
local standard = assert(doc:font('Helvetica'))
local loaded = assert(doc:load_font(fixtures..'/VectisTest.ttf',{encoding='UTF-8'}))
assert(page:text(20,200,'Hello Lua',{font=standard,size=18,color={1,0,0}}))
assert(page:text(20,170,'A中',{font=loaded,size=14}))
local thread = coroutine.create(function() assert(page:text(60,170,'Coroutine')) end)
assert(coroutine.resume(thread))
assert(page:line(10,150,300,150,{line_width=0,color={0,0,1}}))
assert(page:rectangle(10,100,40,30,{fill=true,stroke=true,color={0,0,1}}))
local png = assert(doc:load_image(fixtures..'/pixels.png'))
local jpeg = assert(doc:load_image(fixtures..'/pixels.jpg',{format='jpeg'}))
assert(png:info().width == 2 and png:info().height == 1)
assert(jpeg:info().width == 2 and jpeg:info().height == 1)
assert(page:image(png,10,20,80,40))
assert(page:image(jpeg,100,20,80,40))
local function image_bytes(path)
  local input = assert(io.open(path,'rb'))
  local data = assert(input:read('a'))
  assert(input:close())
  return data
end
local encoded = image_bytes(fixtures..'/pixels.png')
local memory_png = assert(doc:load_image_materialized(encoded))
local memory_jpeg = assert(doc:load_image_materialized(image_bytes(fixtures..'/pixels.jpg'),{format='jpeg'}))
encoded = nil
collectgarbage('collect')
assert(page:image(memory_png,200,20,20,10))
assert(page:image(memory_jpeg,230,20,20,10))
assert(memory_png:close() and memory_jpeg:close())
local other = assert(pdf.new())
local other_page = assert(other:add_page())
local value, err = other_page:image(png,0,0,1,1)
assert(value == nil and err.status == vectis.ERR_INVALID)
value, err = other_page:text(0,0,'foreign',{font=loaded})
assert(value == nil and err.status == vectis.ERR_INVALID)
assert(other_page:text(20,20,'Independent'))
assert(other_page:close())
assert(other:bytes_materialized():find('Independent',1,true))
assert(other:close())
assert(doc:bytes_materialized({max_bytes=8}) == nil)
local bytes = assert(doc:bytes_materialized())
assert(bytes:sub(1,5) == '%PDF-' and bytes:find('%%EOF',1,true))
assert(bytes:find('Hello Lua',1,true) and bytes:find('Lua report',1,true))
assert(not bytes:find('changed after construction',1,true))
assert(bytes:find('FontFile2',1,true) and bytes:find('/Count 1',1,true))
assert(bytes:find('320 240',1,true))
assert(doc:save(root..'/lua-report.pdf'))
local file = assert(io.open(root..'/lua-report.pdf','rb'))
assert(file:read(5) == '%PDF-')
assert(file:close())
for _, callback in ipairs({
  function() return pdf.new({unknown=true}) end,
  function() return doc:add_page({unknown=true}) end,
  function() return page:text(1,2,'text',{color='red'}) end,
  function() return page:text(1,2,'a\0b') end,
  function() return doc:load_font(fixtures..'/VectisTest.ttf',{embed='yes'}) end,
  function() return doc:bytes_materialized({max_bytes=0}) end,
  function() return doc:load_image(fixtures..'/pixels.png',{['format\0ignored']='png'}) end,
}) do assert(not pcall(callback)) end
assert(doc:add_page({width=-1}) == nil)
assert(page:rectangle(0,0,1,1,{color={2,0,0}}) == nil)
assert(doc:load_image(fixtures..'/pixels.png',{format='gif'}) == nil)
assert(page:text(10,10,'Validation preserved the document'))
value, err = doc:load_font(root..'/no-such-font.ttf')
assert(value == nil and err.dependency_code ~= 0)
assert(doc:bytes_materialized() == nil)
assert(doc:reset_error())
value, err = doc:save(root..'/missing-directory/report.pdf')
assert(value == nil and err.operation == 'save' and err.dependency_code ~= 0)
assert(doc:reset_error())
assert(standard:close() and standard:close())
assert(loaded:close() and png:close() and jpeg:close())
assert(page:close())
assert(doc:bytes_materialized():find('Hello Lua',1,true))
local retained = assert(doc:add_page())
assert(doc:close() and doc:close())
assert(not pcall(function() retained:text(0,0,'closed') end))
assert(retained:close() and retained:close())
doc,page,other,other_page,retained = nil,nil,nil,nil,nil
collectgarbage('collect')
collectgarbage('collect')
print('upgrade seam behavior ok')
