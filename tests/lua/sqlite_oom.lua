local sqlite = require('vectis.sqlite.core')
local db <close> = assert(sqlite.open(':memory:'))
assert(db:exec('create table t (id, value)', {}))
assert(db:transaction(function()
  assert(db:exec('insert into t values (?,?)', {1, string.rep('x', 2048)}))
  local q <close> = assert(db:query('select id,value from t', {}))
  assert(q:columns()[2].name == 'value')
  assert(#assert(q:next())[2] == 2048)
  assert(q:next() == nil)
end))
local q <close> = assert(db:prepare('select ?,?'))
assert(q:bind({sqlite.NULL, sqlite.blob('')}))
assert(q:next()[1] == sqlite.NULL)
assert(q:reset())
assert(q:bind({math.mininteger, 'ok'}))
assert(q:next()[2] == 'ok')
return true
