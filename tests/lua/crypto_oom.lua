local crypto=require('vectis.crypto.core')
local key <close> = assert(crypto.load_key({private_key_pem=CRYPTO_PRIVATE_PEM}))
local public <close> = assert(crypto.load_key({public_key_pem=CRYPTO_PUBLIC_PEM}))
assert(key:info().bits==2048 and not public:info().private_key)
local signature=assert(key:sign('binary\0data'))
assert(public:verify('binary\0data',signature))
assert(public:verify('changed',signature)==false)
assert(key:sign('second',{digest='sha512'}))
local secret=string.rep('k',32)
local nonce=string.rep('n',12)
local encrypted=assert(crypto.aes_gcm_encrypt_materialized({key=secret,nonce=nonce,data='binary\0data',aad='context'}))
assert(crypto.aes_gcm_decrypt_materialized({key=secret,nonce=nonce,ciphertext=encrypted.ciphertext,tag=encrypted.tag,aad='context'})=='binary\0data')
assert(crypto.aes_gcm_decrypt_materialized({key=secret,nonce=nonce,ciphertext=encrypted.ciphertext,tag=encrypted.tag,aad='wrong'})==nil)
return true
