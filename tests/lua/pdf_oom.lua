local pdf = require('vectis.pdf.core')
local doc <close> = assert(pdf.new({title='Allocation cleanup',author='Vectis'}))
local page <close> = assert(doc:add_page({width=320,height=240}))
local font <close> = assert(doc:load_font(PDF_TEST_FIXTURES..'/VectisTest.ttf',{encoding='UTF-8'}))
assert(page:text(20,200,'A中',{font=font,color={1,0,0},size=18}))
local image <close> = assert(doc:load_image(PDF_TEST_FIXTURES..'/pixels.png'))
assert(image:info().width == 2)
assert(page:image(image,0,0,20,10))
local memory_image <close> = assert(doc:load_image_materialized(PDF_TEST_PNG))
assert(page:image(memory_image,30,0,20,10))
assert(page:rectangle(10,10,20,20,{fill=true,color={0,0,1}}))
local bytes = assert(doc:bytes_materialized())
assert(bytes:sub(1,5) == '%PDF-' and bytes:find('FontFile2',1,true))
return true
