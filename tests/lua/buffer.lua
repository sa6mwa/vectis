local bytes=require('vectis.buffer')
assert(require('vectis').buffer==bytes)
local function fails(fn,...) assert(not pcall(fn,...)) end
local buffer=assert(bytes.from_materialized('a\0bc'))
assert(buffer:size()==4 and buffer:read_materialized(0,4)=='a\0bc')
assert(buffer:data()==buffer and select(2,buffer:data_mutable())==4)
assert(buffer:resize(8)==buffer and buffer:read_materialized(4,4)=='\0\0\0\0')
local readonly=buffer:borrow(1,3)
local mutable=buffer:borrow(0,4,false)
local capability,size=readonly:data();assert(capability==readonly and size==3)
fails(readonly.data_mutable,readonly);fails(readonly.write,readonly,0,'x')
fails(buffer.resize,buffer,8);fails(buffer.write,buffer,0,'x')
fails(buffer.data_mutable,buffer);assert(select(2,buffer:data())==8)
assert(mutable:data_mutable()==mutable)
assert(mutable:write(2,'Z')==mutable and readonly:read_materialized(0,3)=='\0Zc')
fails(readonly.borrow,readonly,0,1,false)
local child=mutable:borrow(2,1,false)
buffer:close();buffer:close();fails(buffer.size,buffer)
assert(readonly:read_materialized(0,3)=='\0Zc')
mutable:close();readonly:close();fails(readonly.size,readonly)
assert(child:read_materialized(0,1)=='Z');child:close()
local empty=assert(bytes.new(0));local zero=empty:borrow(0,0)
assert(zero:read_materialized(0,0)=='' and select(2,zero:data())==0)
zero:close();assert(empty:resize(2)==empty);assert(empty:read_materialized(0,2)=='\0\0')
empty:close()
for _,bad in ipairs({-1,1.5,'18446744073709551616','1\0',{},true}) do fails(bytes.new,bad) end
local small=assert(bytes.new('4'))
fails(small.read_materialized,small,4,1);fails(small.read_materialized,small,'18446744073709551615',1)
fails(small.read_materialized,small,0,65537);fails(small.write,small,0,('x'):rep(65537))
fails(small.borrow,small,4,1);fails(small.borrow,small,0,1,'false')
local retained=small:borrow(0,4,false);small=nil;collectgarbage('collect')
assert(retained:write(0,'data')==retained and retained:read_materialized(0,4)=='data')
retained:close()
local owner=assert(bytes.new(1));local span=owner:borrow(0,1)
getmetatable(span).__gc(span);assert(owner:resize(2)==owner)
assert(pcall(getmetatable(owner).__gc,io.stdout) and io.type(io.stdout)=='file')
owner:close()
do local owned <close> = assert(bytes.new(2));local view <close> = owned:borrow(0,2);assert(view:size()==2) end
collectgarbage('collect')
do
  local parent=assert(bytes.new(4));local span=parent:borrow(0,4,false)
  local one=parent:lock_writes();local two=span:lock_writes();parent:close()
  fails(span.write,span,0,'x');fails(span.data_mutable,span)
  assert(span:read_materialized(0,4)=='\0\0\0\0')
  one:close();one:close();fails(span.write,span,0,'x')
  two:close();assert(span:write(0,'data')==span);span:close()
end
