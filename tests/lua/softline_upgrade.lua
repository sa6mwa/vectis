local v,sl=require('vectis'),require('softline')
local editor=assert(v.terminal.editor({line_max_len=128,history_max_len=4}))
assert(editor:set_prompt_queue(true,4,2))
local first=assert(editor:inject_queued_prompt('first'))
local second=assert(editor:inject_steer_prompt('second'))
assert(first~=second and editor:queue_info(1).held)
assert(not editor:queue_take(1))
assert(not editor:queue_approve(second)) -- approval is FIFO
assert(editor:queue_replace(1,'edited'))
assert(editor:queue_info(1).id==first and editor:queue_info(1).held)
assert(editor:queue_approve(first))
local text,id=editor:queue_take(1)
assert(text=='edited' and id==first)
assert(editor:queue_info(1).mode==sl.QUEUE_MODE_STEER)
assert(editor:set_auto_approval(true))
assert(editor:get_auto_approval() and not editor:queue_info(1).held)
text,id=editor:queue_take(1)
assert(text=='second' and id==second)
local appended,emitter={},nil
assert(editor:history_set_backend('vectis-upgrade',{
  load=function(key,emit)
    assert(key=='vectis-upgrade');emitter=emit;assert(emit('seed'));return true
  end,
  append=function(key,prompt)
    assert(key=='vectis-upgrade');appended[#appended+1]=prompt;return true
  end,
}))
assert(not pcall(emitter,'late'))
assert(editor:history_add('recorded'))
assert(#appended==1 and appended[1]=='recorded')
assert(editor:history_set_backend('failing',{append=function() error('history fault') end}))
local ok,status,message=editor:history_add('rejected')
assert(not ok and status and message:find('history fault',1,true))
assert(editor:history_close())
assert(editor:history_add('local'))
assert(editor:set_buffer('draft'))
assert(not editor:output_stream_reconcile())
assert(editor:output_stream_begin())
assert(editor:output_stream_reconcile())
assert(editor:output_stream_write('bounded output\n'))
assert(editor:output_stream_end())
assert(editor:buffer()=='draft')
assert(sl.KEY_ACTION_SUSPEND and sl.READLINE_SUSPENDED)
editor:close()
collectgarbage('collect')
print('upgrade seam behavior ok: softline')
